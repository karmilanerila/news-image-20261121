def _load_font(b64, size):
    raw = zlib.decompress(base64.b64decode(b64))
    ascent, n = struct.unpack_from("<hH", raw, 0)
    pos = 4
    glyphs = {}
    for _ in range(n):
        cp, adv, xo, yo, w, h = struct.unpack_from("<IfbbBB", raw, pos)
        pos += 12
        nb = (w * h + 1) // 2
        glyphs[cp] = (adv, xo, yo, w, h, raw[pos:pos + nb])
        pos += nb
    nkern, = struct.unpack_from("<H", raw, pos)
    pos += 2
    kern = {}
    for _ in range(nkern):
        ca, cb, k = struct.unpack_from("<IIf", raw, pos)
        pos += 12
        kern[(ca, cb)] = k
    return (size, ascent, glyphs, kern)


