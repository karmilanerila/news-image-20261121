class Canvas:
    """A plain RGB bytearray canvas with a small PIL-like drawing API.
    Coordinates are truncated to int like Pillow's; rectangle/ellipse
    boxes are inclusive on both ends, like Pillow's."""

    def __init__(self, w, h, bg):
        self.w = w
        self.h = h
        self.stride = w * 3
        self.buf = bytearray(bytes(bg) * (w * h))

    def _fill_rect(self, x0, y0, x1, y1, color):
        x0 = max(0, int(x0))
        y0 = max(0, int(y0))
        x1 = min(self.w - 1, int(x1))
        y1 = min(self.h - 1, int(y1))
        if x1 < x0 or y1 < y0:
            return
        n = x1 - x0 + 1
        row = bytes(color) * n
        stride = self.stride
        for y in range(y0, y1 + 1):
            o = y * stride + x0 * 3
            self.buf[o:o + 3 * n] = row

    def rectangle(self, x0, y0, x1, y1, fill=None, outline=None, width=1):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        if fill is not None:
            self._fill_rect(x0, y0, x1, y1, fill)
        if outline is not None:
            w = max(1, int(width))
            self._fill_rect(x0, y0, x1, y0 + w - 1, outline)
            self._fill_rect(x0, y1 - w + 1, x1, y1, outline)
            self._fill_rect(x0, y0, x0 + w - 1, y1, outline)
            self._fill_rect(x1 - w + 1, y0, x1, y1, outline)

    def line(self, x0, y0, x1, y1, fill, width=1):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        w = max(1, int(width))
        half = w // 2
        if y0 == y1:
            if x0 > x1:
                x0, x1 = x1, x0
            # Pillow draws a wide horizontal line downward from y.
            self._fill_rect(x0, y0, x1, y0 + w - 1, fill)
            return
        if x0 == x1:
            if y0 > y1:
                y0, y1 = y1, y0
            # Pillow draws a wide vertical line rightward from x.
            self._fill_rect(x0, y0, x0 + w - 1, y1, fill)
            return
        dx = abs(x1 - x0)
        dy = -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            self._fill_rect(x0 - half, y0 - half,
                            x0 - half + w - 1, y0 - half + w - 1, fill)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def ellipse(self, x0, y0, x1, y1, fill=None, outline=None, width=1):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        cx = (x0 + x1) / 2.0
        cy = (y0 + y1) / 2.0
        rx = (x1 - x0) / 2.0
        ry = (y1 - y0) / 2.0
        if rx <= 0 or ry <= 0:
            return
        if fill is not None:
            for y in range(y0, y1 + 1):
                t = (y - cy) / ry
                if t < -1.0 or t > 1.0:
                    continue
                dx = rx * math.sqrt(1.0 - t * t)
                self._fill_rect(int(cx - dx), y, int(cx + dx), y, fill)
        if outline is not None:
            w = max(1, int(width))
            half = w // 2
            per = 2 * math.pi * math.sqrt((rx * rx + ry * ry) / 2.0)
            n = max(24, int(per) + 1)
            for i in range(n + 1):
                a = 2 * math.pi * i / n
                px = int(cx + rx * math.cos(a))
                py = int(cy + ry * math.sin(a))
                self._fill_rect(px - half, py - half,
                                px - half + w - 1, py - half + w - 1, outline)

    def arc(self, x0, y0, x1, y1, start, end, fill, width=1):
        # Angles in degrees, 0 = 3 o'clock, increasing clockwise (y down).
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        cx = (x0 + x1) / 2.0
        cy = (y0 + y1) / 2.0
        rx = (x1 - x0) / 2.0
        ry = (y1 - y0) / 2.0
        w = max(1, int(width))
        half = w // 2
        span = end - start
        steps = max(2, int(abs(span) * max(rx, ry) * math.pi / 180.0) + 1)
        for i in range(steps + 1):
            a = math.radians(start + span * i / steps)
            px = int(cx + rx * math.cos(a))
            py = int(cy + ry * math.sin(a))
            self._fill_rect(px - half, py - half,
                            px - half + w - 1, py - half + w - 1, fill)

    def polygon(self, pts, fill):
        if not pts:
            return
        ys = [p[1] for p in pts]
        y0 = max(0, int(math.floor(min(ys))))
        y1 = min(self.h - 1, int(math.ceil(max(ys))))
        n = len(pts)
        for y in range(y0, y1 + 1):
            yc = y + 0.5
            xs = []
            for i in range(n):
                xa, ya = pts[i]
                xb, yb = pts[(i + 1) % n]
                if (ya <= yc < yb) or (yb <= yc < ya):
                    t = (yc - ya) / (yb - ya)
                    xs.append(xa + t * (xb - xa))
            xs.sort()
            for i in range(0, len(xs) - 1, 2):
                self._fill_rect(int(xs[i]), y, int(xs[i + 1]), y, fill)

    def _blit(self, gx0, gy0, w, h, data, color):
        if w <= 0 or h <= 0:
            return
        x0 = int(gx0)
        y0 = int(gy0)
        r0 = max(0, -y0)
        r1 = min(h, self.h - y0)
        c0 = max(0, -x0)
        c1 = min(w, self.w - x0)
        if r0 >= r1 or c0 >= c1:
            return
        buf = self.buf
        stride = self.stride
        r, g, b = color
        for rr in range(r0, r1):
            y = y0 + rr
            o = y * stride + (x0 + c0) * 3
            base = rr * w + c0
            for cc in range(c0, c1):
                idx = base + (cc - c0)
                byte = data[idx >> 1]
                a = (byte >> 4) if (idx & 1) == 0 else (byte & 15)
                if a == 0:
                    o += 3
                    continue
                if a == 15:
                    buf[o] = r
                    buf[o + 1] = g
                    buf[o + 2] = b
                else:
                    inv = 15 - a
                    buf[o] = (r * a + buf[o] * inv) // 15
                    buf[o + 1] = (g * a + buf[o + 1] * inv) // 15
                    buf[o + 2] = (b * a + buf[o + 2] * inv) // 15
                o += 3

    def text(self, x, y, s, fnt, fill):
        # y is the ascender top (Pillow's default "la" anchor).
        glyphs = fnt[2]
        kern = fnt[3]
        q = glyphs.get(63)
        cx = float(x)
        yi = int(round(y))
        prev = None
        for ch in s:
            cp = ord(ch)
            g = glyphs.get(cp) or q
            if g is None:
                continue
            if prev is not None:
                cx += kern.get((prev, cp), 0.0)
            adv, xo, yo, w, h, data = g
            self._blit(int(round(cx)) + xo, yi + yo, w, h, data, fill)
            cx += adv
            prev = cp

    def textlength(self, s, fnt):
        glyphs = fnt[2]
        kern = fnt[3]
        q = glyphs.get(63)
        total = 0.0
        prev = None
        for ch in s:
            cp = ord(ch)
            g = glyphs.get(cp) or q
            if g is not None:
                if prev is not None:
                    total += kern.get((prev, cp), 0.0)
                total += g[0]
                prev = cp
        return total


# ---------------------------------------------------------------- text tools
def wrap(cv, text, fnt, width):
    """Greedy word wrap; returns a list of lines that fit `width`."""
    lines, cur = [], ""
    for word in text.split():
        trial = (cur + " " + word).strip()
        if cv.textlength(trial, fnt) <= width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


def draw_wrapped(cv, x, y, text, fnt, width, fill=INK, spacing=2,
                 max_lines=None, line_h=None):
    """Draw wrapped text; returns (lines_drawn, height_used)."""
    lines = wrap(cv, text, fnt, width)
    if max_lines is not None and len(lines) > max_lines:
        lines = lines[:max_lines]
        while lines and cv.textlength(lines[-1] + " ...", fnt) > width:
            lines[-1] = lines[-1][:-1].rstrip()
        lines[-1] = lines[-1] + " ..."
    lh = line_h or int(fnt[0] * 1.22)
    for i, ln in enumerate(lines):
        cv.text(x, y + i * lh, ln, fnt, fill)
    return len(lines), len(lines) * lh


