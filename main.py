def build():
    cv = Canvas(W, H, PAPER)
    draw_masthead(cv)
    draw_stats(cv)
    # leads
    lx, ly, lw, gap = 24, 190, (W - 48 - 2 * 10) / 3, 10
    for i, lead in enumerate(LEADS):
        draw_lead(cv, lx + i * (lw + gap), ly, lw, lead)
    # cards
    section_rule(cv, 24, 438, W - 48, "INSIDE TODAY")
    cw, ch, cg = (W - 48 - 3 * 8) / 4, 90, 8
    for i, (kick, head, deck) in enumerate(CARDS):
        cx = 24 + (i % 4) * (cw + cg)
        cy = 460 + (i // 4) * (ch + cg)
        draw_card(cv, cx, cy, cw, ch, kick, head, deck, i)
    # bottom row: map + timeline
    by = 758
    draw_map(cv, 24, by, 620, 152)
    draw_right(cv, 656, by, 344)
    # brief strip
    draw_brief_strip(cv, 24, 918, W - 48)
    cv.line(24, 1006, W - 24, 1006, fill=RULE, width=1)
    draw_footer(cv)
    return cv


def main():
    cv = build()
    data = png_bytes(cv.buf, W, H)
