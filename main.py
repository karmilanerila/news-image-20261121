# ---------------------------------------------------------------- PNG encoder
# RGB, 8 bit, no interlace. Per-scanline filter choice among 0 (None),
# 1 (Sub) and 2 (Up): the filter with the smallest sum of absolute
# signed byte values wins; ties prefer filter 0. Deterministic.
_ABS = bytes(abs(i if i < 128 else i - 256) for i in range(256))


def _png_chunk(typ, data):
    return (struct.pack(">I", len(data)) + typ + data
            + struct.pack(">I", zlib.crc32(typ + data) & 0xFFFFFFFF))


def png_bytes(buf, w, h):
    stride = w * 3
    out = bytearray()
    zeros = bytes(stride)
    prev = zeros
    for y in range(h):
        row = bytes(buf[y * stride:(y + 1) * stride])
        f0 = row
        s0 = sum(f0.translate(_ABS))
        f1 = row[:3] + bytes((a - b) & 0xFF for a, b in zip(row[3:], row))
        s1 = sum(f1.translate(_ABS))
        f2 = bytes((a - b) & 0xFF for a, b in zip(row, prev))
        s2 = sum(f2.translate(_ABS))
        if s1 < s0 and s1 <= s2:
            out.append(1)
            out += f1
        elif s2 < s0:
            out.append(2)
            out += f2
        else:
            out.append(0)
            out += f0
        prev = row
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    idat = zlib.compress(bytes(out), 9)
    return (b"\x89PNG\r\n\x1a\n" + _png_chunk(b"IHDR", ihdr)
            + _png_chunk(b"IDAT", idat) + _png_chunk(b"IEND", b""))


