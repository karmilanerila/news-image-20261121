def art_riyadh(cv, x, y, w, h):
    """Riyadh at night: skyline, tall PIF tower, intercept bursts."""
    cv.rectangle(x, y, x + w, y + h, fill=NIGHT)
    for sx, sy in [(0.07, 0.10), (0.20, 0.05), (0.33, 0.13), (0.48, 0.07),
                   (0.60, 0.12), (0.74, 0.06), (0.88, 0.11), (0.95, 0.22),
                   (0.42, 0.18), (0.12, 0.22)]:
        cv.ellipse(x + sx * w - 1, y + sy * h - 1, x + sx * w + 1, y + sy * h + 1,
                   fill=(215, 215, 195))
    # intercept bursts: dotted trails up to starbursts
    for (tx, ty) in [(0.24, 0.30), (0.55, 0.24), (0.82, 0.32)]:
        bx, by = x + tx * w, y + ty * h
        for k in range(1, 5):
            cv.ellipse(bx - k * 7, by + k * 11 - 1, bx - k * 7 + 2,
                       by + k * 11 + 1, fill=(255, 200, 120))
        for ang in range(0, 360, 45):
            r = 10
            ex = bx + r * math.cos(math.radians(ang))
            ey = by + r * math.sin(math.radians(ang))
            cv.line(bx, by, ex, ey, fill=(255, 170, 60), width=2)
        cv.ellipse(bx - 4, by - 4, bx + 4, by + 4, fill=(255, 220, 140))
    # skyline
    base = y + 0.80 * h
    for bx, bw, bh in [(0.00, 0.07, 0.16), (0.09, 0.06, 0.22), (0.17, 0.08, 0.13),
                       (0.27, 0.06, 0.19), (0.60, 0.07, 0.15), (0.69, 0.06, 0.21),
                       (0.77, 0.07, 0.12), (0.90, 0.08, 0.17)]:
        cv.rectangle(x + bx * w, base - bh * h, x + (bx + bw) * w, base,
                     fill=(8, 10, 18))
    # PIF tower: tall, tapering, lit windows
    tx0, tx1 = x + 0.40 * w, x + 0.52 * w
    cv.polygon([(tx0, base), (tx0 + 0.02 * w, y + 0.34 * h),
                (tx1 - 0.02 * w, y + 0.34 * h), (tx1, base)], fill=(10, 12, 22))
    for wy in range(6):
        yy = y + (0.40 + wy * 0.06) * h
        cv.line(tx0 + 0.03 * w, yy, tx1 - 0.03 * w, yy, fill=(255, 210, 110), width=1)
    # ground
    cv.rectangle(x, base, x + w, y + h, fill=(30, 34, 48))
    cv.rectangle(x, y, x + w, y + h, outline=(24, 24, 24), width=1)


def art_cop31(cv, x, y, w, h):
    """COP31 hall: globe, sun rays, rows of delegates, draft papers."""
    cv.rectangle(x, y, x + w, y + h, fill=(238, 240, 226))
    cx, cy = x + 0.62 * w, y + 0.46 * h
    # sun rays
    for k in range(12):
        ang = math.radians(k * 30)
        cv.line(cx + 0.14 * w * math.cos(ang), cy + 0.14 * h * math.sin(ang) * 1.4,
                cx + 0.21 * w * math.cos(ang), cy + 0.21 * h * math.sin(ang) * 1.4,
                fill=(232, 190, 90), width=3)
    # globe
    cv.ellipse(cx - 0.11 * w, cy - 0.11 * w, cx + 0.11 * w, cy + 0.11 * w,
               fill=TEAL, outline=(10, 70, 70), width=2)
